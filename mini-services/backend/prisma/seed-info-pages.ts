async function main() {
  console.log('999 — Три девятки — Seed default info pages')
  console.log('==================================')
  console.log('')

  const force = process.argv.includes('--force')

  let created = 0
  let skipped = 0
  let updated = 0

  for (let i = 0; i < DEFAULT_PAGES.length; i++) {
    const p = DEFAULT_PAGES[i]
    const existing = await prisma.infoPage.findUnique({ where: { slug: p.slug } })

    if (existing) {
      if (force) {
        await prisma.infoPage.update({
          where: { id: existing.id },
          data: {
            title: p.title,
            subtitle: p.subtitle,
            icon: p.icon,
            content: p.content,
            metaDescription: p.metaDescription,
            // Don't override order/isPublished/showInMenu — admin may have customized them
          },
        })
        console.log(`  ↻ updated: ${p.slug} (${p.title})`)
        updated++
      } else {
        console.log(`  → skip:    ${p.slug} (already exists, use --force to overwrite)`)
        skipped++
      }
    } else {
      await prisma.infoPage.create({
        data: {
          slug: p.slug,
          title: p.title,
          subtitle: p.subtitle,
          icon: p.icon,
          content: p.content,
          metaDescription: p.metaDescription,
          order: i,
          isPublished: true,
          showInMenu: true,
          images: '[]',
        },
      })
      console.log(`  + created: ${p.slug} (${p.title})`)
      created++
    }
  }

  console.log('')
  console.log(`Done. Created: ${created}, updated: ${updated}, skipped: ${skipped}`)
  console.log(`Total info pages in DB: ${await prisma.infoPage.count()}`)
  console.log('')
  console.log('All pages are fully editable via Studio → "Инфо-страницы".')
}

main()
  .then(() => prisma.$disconnect())
  .catch((e) => {
    console.error('Seed failed:', e)
    prisma.$disconnect()
    process.exit(1)
  })
